// Writes src/migration-list.ts from src/migrations/*.sql. Run `pnpm gen:migrations`
// after adding a migration and commit the result; migration-list.test.ts fails
// on a list that has drifted from the files.
import { execFileSync } from 'node:child_process';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'src', 'migrations');
const entries = readdirSync(dir)
  .filter((name) => name.endsWith('.sql'))
  .sort()
  .map((name) => ({
    id: `audit-${name.slice(0, -4)}`,
    sql: readFileSync(join(dir, name), 'utf8'),
  }));
const out = join(root, 'src', 'migration-list.ts');
writeFileSync(
  out,
  `// Generated by scripts/gen-migration-list.mjs from migrations/*.sql. Do not edit.
export interface AuditMigration {
  /** Stable across releases: \`audit-\` and the file name without \`.sql\`. */
  readonly id: string;
  readonly sql: string;
}

export const migrations: readonly AuditMigration[] = ${JSON.stringify(entries, null, 2)};
`,
);
execFileSync('pnpm', ['exec', 'biome', 'format', '--write', out], { cwd: root, stdio: 'inherit' });
